#!/usr/bin/env bash
# =====================================================================
# 文件已更换为 A 模式所需的路径工具。
# Claude Code 用 cwd 编码作为 ~/.claude/projects/ 下的目录名:
#   /home/fengye            -> -home-fengye
#   /home/fengye/code/foo   -> -home-fengye-code-foo
# `-` 既是「根」也是「路径分隔符」的编码,故「绝对路径还原」有歧义,
# 这正是插件引入可选「根替换规则 ROOT_MAP」的原因:它提供了必要的前缀边界。
# =====================================================================

# 绝对路径(或相对路径) -> cwd 编码(前导 - 表示根)
cwd_encode() {
  local p="${1}"
  p="${p#/}"
  echo "-${p//\//-}"
}

# 去掉一个编码的前导 -,把剩余的 - 还原为 /,用于拼接到已知本机路径后。
# 例: "-code-foo" -> "code/foo"
cwd_decode_suffix() {
  local s="${1}"
  s="${s#-}"
  echo "${s//-//}"
}