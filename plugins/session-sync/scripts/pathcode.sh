#!/usr/bin/env bash
# =====================================================================
# 会话目录编码工具(跨平台)。
# Claude Code 把启动目录的绝对路径编码成 ~/.claude/projects/ 下的目录名,规则:
#   - 前置一个 '-' 表示路径根;
#   - 路径里每个「连续的非字母数字段」折叠成一个 '-'。
# 例: /home/fengye => -home-fengye ; C:\Users\me\proj => -C-Users-me-proj
# `\` 与 `/` 先归一(Windows 下 `C:\` 与 `C:/` 编码相同)。
# 绝对路径解码有歧义('-' 同时是根与分隔符的记号),故插件以「根替换规则
# ROOT_MAP」提供必要的前缀边界,而非凭空还原路径。
# =====================================================================

# 绝对/相对路径 -> cwd 编码(跨平台,含 Windows `\`)
cwd_encode() {
  local p="$1"
  p="${p//\\//}"                       # Windows 反斜杠先转正斜杠
  p="${p#/}"                           # 去掉根处的前导斜杠(那个 '-' 由我们是 prefix 表示)
  p="$(printf '%s' "$p" | perl -pe 's/[^A-Za-z0-9]+/-/g')"
  printf -- "-%s" "$p"
}

# 编码的相对后缀 -> 相对路径(去前导 '-',其余 '-' 还原为 '/')
# 例: "-code-foo" -> "code/foo"(用于拼接到已知本机路径后)
cwd_decode_suffix() {
  local s="$1"
  s="${s#-}"
  echo "${s//-//}"
}