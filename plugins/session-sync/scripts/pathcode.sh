#!/usr/bin/env bash
# =====================================================================
# 会话目录编码工具(跨平台)。
# Claude Code 把启动目录的绝对路径编码成 ~/.claude/projects/ 下的目录名,规则:
#   把路径里「每个」非字母数字字符都换成 '-'(`\` 与 `/` 先归一)。
#   根 '/' 自然变成前导 '-';含连续分隔服(如 Windows 驱动盘 `D:\`)会得多个 '-':
#      /home/fengye        => -home-fengye
#      D:\ai-project       => D--ai-project       (':' 和 '/' 各一个 '-')
#      C:\Users\me\proj    => C--Users-me-proj
# ⚠ 这是 Claude Code 的「逐字符」规则(非「压连续段」)。早期本函数误用后者
#   (`[^A-Za-z0-9]+` 折叠),导致含连续分隔服的路径(尤其 Windows 盘根)编码错位,
#   会话落错 project 目录、claude --resume 找不到 —— 已修正为逐字符以对齐。
# 绝对路径解码有歧义('-' 同时是根与分隔符的记号),故插件以「根替换规则
# ROOT_MAP」提供必要的前缀边界,而非凭空还原路径。
# =====================================================================

# 绝对/相对路径 -> cwd 编码(跨平台,含 Windows `\`)
cwd_encode() {
  local p="$1"
  p="${p//\\//}"                       # Windows 反斜杠先转正斜杠
  printf '%s' "$p" | perl -CS -pe 's/[^A-Za-z0-9]/-/g'
}

# 编码的相对后缀 -> 相对路径(去前导 '-',其余 '-' 还原为 '/')
# 例: "-code-foo" -> "code/foo"(用于拼接到已知本机路径后)
cwd_decode_suffix() {
  local s="$1"
  s="${s#-}"
  echo "${s//-//}"
}